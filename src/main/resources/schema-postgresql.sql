CREATE TABLE IF NOT EXISTS monitor_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    kind VARCHAR(16) NOT NULL,
    method VARCHAR(10),
    path VARCHAR(500),
    query VARCHAR(500),
    status INTEGER,
    duration_ms BIGINT,
    ip VARCHAR(64),
    username VARCHAR(120),
    user_email VARCHAR(160),
    visitor_id VARCHAR(64),
    session_id VARCHAR(64),
    user_agent VARCHAR(400),
    browser VARCHAR(40),
    os VARCHAR(40),
    device VARCHAR(20),
    country VARCHAR(80),
    city VARCHAR(120),
    label VARCHAR(500),
    detail VARCHAR(1000),
    app_version VARCHAR(40)
);

ALTER TABLE monitor_logs ADD COLUMN IF NOT EXISTS user_email VARCHAR(160);
CREATE INDEX IF NOT EXISTS idx_monitor_logs_created ON monitor_logs (created_at);
CREATE INDEX IF NOT EXISTS idx_monitor_logs_kind ON monitor_logs (kind);
CREATE INDEX IF NOT EXISTS idx_monitor_logs_visitor ON monitor_logs (visitor_id);

